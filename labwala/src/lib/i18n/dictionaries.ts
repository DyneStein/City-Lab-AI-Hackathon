export const dictionaries = { en, ur, pa } as const;
export type Lang = keyof typeof dictionaries;
export const LANGS: { code: Lang; label: string; native: string; dir: "ltr" | "rtl"; bcp47: string }[] = [
  { code: "en", label: "English", native: "English", dir: "ltr", bcp47: "en-PK" },
  { code: "ur", label: "Urdu", native: "اردو", dir: "rtl", bcp47: "ur-PK" },
  { code: "pa", label: "Punjabi", native: "پنجابی", dir: "rtl", bcp47: "pa-PK" },
];

export const langMeta = (l: Lang) => LANGS.find((x) => x.code === l)!;

export function fmt(s: string, vars: Record<string, string | number>) {
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}

/** Date formatting in the user's language (Punjabi uses the shared Urdu month names). */
export function formatDate(d: string | number | Date, lang: Lang, style: "short" | "long" = "short") {
  const locale = lang === "en" ? "en-GB" : "ur-PK";
  return new Intl.DateTimeFormat(locale, { day: "numeric", month: style === "long" ? "long" : "short", year: "numeric" }).format(new Date(d));
}
